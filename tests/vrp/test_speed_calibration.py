# What the model cannot carry
# --------------------------------------------------------------------------

def test_arc_classes_are_fitted_apart_and_never_averaged_together():
    """§12.2 fits per arc class; §6.3 stores a profile per arc.

    `Problem.speed_profile` carries one profile for a whole instance, so there
    is nowhere to put a per-class fit. The calibration keeps the classes apart
    and makes the caller name one, rather than collapsing them into a single
    profile that describes no road in particular.
    """
    problem = a_town()
    mixed = fit(traversals(problem, a_week(problem, peak()), HOUR),
                minimum=3, bucket_seconds=HOUR, buckets=24)

    assert all(isinstance(key, ArcKey) for key in mixed.by_key)
    with pytest.raises(KeyError, match="motorway"):
        mixed.profile("motorway")
