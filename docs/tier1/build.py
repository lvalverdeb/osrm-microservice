def _comments(raw: str, entry: re.Pattern[str]) -> dict[str, str]:
    """Attach each contiguous comment block to the entry written below it."""
    notes: dict[str, str] = {}
    buffer: list[str] = []
    for line in raw.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            buffer.append(stripped.lstrip("#").strip())
        elif (found := entry.match(stripped)):
            if buffer:
                notes[found.group(1)] = " ".join(buffer)
            buffer = []
        elif not stripped:
            buffer = []
    return notes


def _locked(lockfile: str) -> dict[str, str]:
    """Resolved versions, by package name, from a TOML lockfile."""
    return {package["name"]: package["version"]
            for package in tomllib.loads(read(lockfile))["package"]}


def _rust_dependencies() -> list[tuple[str, ...]]:
    """The gateway's crates: requirement, resolved version and rationale."""
    manifest = tomllib.loads(read("gateway/Cargo.toml"))
    locked = _locked("gateway/Cargo.lock")
    notes = _comments(read("gateway/Cargo.toml"),
                      re.compile(r"^([a-z0-9_-]+)\s*="))
    rows = []
    for section in ("dependencies", "dev-dependencies"):
        for name, spec in sorted(manifest.get(section, {}).items()):
            wanted = spec if isinstance(spec, str) else spec.get("version", "")
            rows.append((f"`{name}`", section, f"`{wanted}`",
                         f"`{locked.get(name, '—')}`", notes.get(name, "")))
    return rows


def _python_dependencies() -> list[tuple[str, ...]]:
    """The tooling's packages: requirement, resolved version and rationale."""
    manifest = tomllib.loads(read("pyproject.toml"))["project"]
    locked = _locked("uv.lock")
    notes = _comments(read("pyproject.toml"), re.compile(r'^"([A-Za-z0-9_.-]+)'))
    groups = [("dependencies", manifest.get("dependencies", []))]
    groups += [(f"optional: {name}", items) for name, items
               in sorted(manifest.get("optional-dependencies", {}).items())]
    return [(f"`{re.split(r'[><=~!\[]', item)[0]}`", group, f"`{item}`",
             f"`{locked.get(re.split(r'[><=~!\[]', item)[0], '—')}`",
             notes.get(re.split(r"[><=~!\[]", item)[0], ""))
            for group, items in groups for item in items]


