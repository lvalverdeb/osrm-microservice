#!/usr/bin/env python3
"""Tier 1 documentation: what the sources can state about themselves.

Thirteen documents, none of them authored. Each is read out of the thing it
describes -- the OpenAPI document the compiled gateway publishes, the settings
table it reads its environment through, the dataclasses the solver validates
against, the Makefile, the lockfiles -- so no document here can describe an
endpoint, a setting or a field that no longer exists.

That is the whole claim of Tier 1 and the reason these files are committed
rather than built on demand: a reader with no toolchain still gets them, and
`tests/test_tier1_docs.py` fails the suite when the committed copy stops
matching a fresh build. It is the contract
`test_the_generated_catalogue_matches_its_source` already holds
`docs/TDD/vrp-catalogue-v2.1.md` to.

Nothing here is a judgement. Anything that needs one -- why the architecture is
shaped this way, what the SLOs are, whether a gap matters -- belongs in a
written document, not in this build.

Run: `make tier1`. The gateway binary must be built first, because documents 01
and 02 come from a live `/openapi.json` rather than from a parse of the Rust.

An optional argument writes the set somewhere else, which is how the freshness
test builds a fresh copy without disturbing the committed one.
"""

from __future__ import annotations

import ast
import dataclasses
import json
import re
import sys
import tomllib
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any, NamedTuple

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]

BANNER = ("<!-- Generated by docs/tier1/build.py. Do not edit by hand; "
          "run `make tier1`. -->")

# Where the documents land. Replaced by `main` when an argument asks for it.
DESTINATION = HERE

# The trees that count as this system's own source, for the citation scan.
SOURCE_TREES = ("vrp", "tests", "examples/src", "examples/tools", "parity",
                "loadtest", "gateway/src", "rust-spike/src")

# The identifier families the code cites. Defined by the specification, but
# their use is in the code, which is what this scan reads.
IDENTIFIER = re.compile(
    r"\b(FR|NFR|T|CON|MTX|INV|DYN|AC|ALG|DEC|US|UC|E)-(\d{1,3}(?:\.\d+)?)\b")


class Doc(NamedTuple):
    """One generated document: where it lands and what it was read from."""

    slug: str
    title: str
    sources: tuple[str, ...]


def read(relative: str) -> str:
    """Read one repository file as text.

    Args:
        relative: Path relative to the repository root.

    Returns:
        The file's contents.
    """
    return (REPO / relative).read_text()


def relative(path: Path) -> str:
    """Render a path the way a document should cite it."""
    return path.relative_to(REPO).as_posix()


def cell(value: object) -> str:
    """Flatten a value onto a single markdown table cell."""
    return " ".join(str(value).split()).replace("|", r"\|")


def table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> list[str]:
    """Render a markdown table, or a placeholder when there are no rows."""
    body = [f"| {' | '.join(cell(value) for value in row)} |" for row in rows]
    if not body:
        return ["*(none)*", ""]
    head = f"| {' | '.join(headers)} |"
    rule = "|" + "|".join("---" for _ in headers) + "|"
    return [head, rule, *body, ""]


def paragraph(raw: str | None) -> list[str]:
    """A prose block, empty when the source carries no description."""
    return [raw.strip(), ""] if raw and raw.strip() else []


def first_line(raw: str | None) -> str:
    """The opening line of a docstring or description."""
    return (raw or "").strip().split("\n")[0]


def summary(raw: str | None) -> str:
    """The first sentence of a description, for an index column."""
    flat = " ".join((raw or "").split())
    head = flat.split(". ")[0]
    return head if len(head) <= 160 else head[:157] + "…"


def identifiers(raw: str) -> list[str]:
    """Every requirement identifier cited in a piece of text, deduplicated."""
    found = {f"{family}-{number}" for family, number in IDENTIFIER.findall(raw)}
    return sorted(found, key=sort_key)


def sort_key(identifier: str) -> tuple[str, float]:
    """Order identifiers by family, then numerically rather than as text."""
    family, _, number = identifier.partition("-")
    return family, float(number)


def sources_in(tree: str, suffix: str = ".py") -> list[Path]:
    """Every source file of one kind under a tree, in path order."""
    return sorted(path for path in (REPO / tree).rglob(f"*{suffix}")
                  if "__pycache__" not in path.parts)


def docstring_of(path: Path) -> str:
    """A module's docstring, or an empty string when it has none."""
    return ast.get_docstring(ast.parse(path.read_text())) or ""


def emit(slug: str, title: str, sources: Sequence[str],
         body: Sequence[str]) -> Doc:
    """Write one document and record what it came from.

    Args:
        slug: File name within `docs/tier1/`.
        title: Level-one heading.
        sources: Repository paths the content was read from.
        body: Markdown lines below the heading.

    Returns:
        The document's index entry.
    """
    derived = ", ".join(f"`{source}`" for source in sources)
    lines = [BANNER, "", f"# {title}", "", f"*Derived from {derived}.*", "",
             *body]
    (DESTINATION / slug).write_text("\n".join(lines).rstrip() + "\n")
    return Doc(slug, title, tuple(sources))


