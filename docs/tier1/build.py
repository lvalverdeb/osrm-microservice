def _message(node: ast.expr) -> str:
    """Render a `_require` message, keeping f-string placeholders visible."""
    if isinstance(node, ast.Constant):
        return str(node.value)
    if isinstance(node, ast.JoinedStr):
        return "".join(part.value if isinstance(part, ast.Constant) else "{…}"
                       for part in node.values)
    return ""


def _constructor_rules() -> dict[str, list[str]]:
    """Every `_require` message, by the class whose constructor reports it."""
    rules: dict[str, list[str]] = {}
    for node in ast.parse(read("vrp/model.py")).body:
        if not isinstance(node, ast.ClassDef):
            continue
        messages = [_message(call.args[1]) for call in ast.walk(node)
                    if isinstance(call, ast.Call)
                    and getattr(call.func, "id", "") == "_require"
                    and len(call.args) > 1]
        rules[node.name] = sorted({message for message in messages if message})
    return rules


def _default(field: dataclasses.Field) -> str:
    """How a field is filled when the caller omits it."""
    if field.default is not dataclasses.MISSING:
        return f"`{field.default!r}`"
    if field.default_factory is not dataclasses.MISSING:
        return f"`{field.default_factory.__name__}()`"
    return "**required**"


def _entity(entity: type, rules: Sequence[str]) -> list[str]:
    """One domain type: what it is, its fields, and what it refuses."""
    lines = [f"### {entity.__name__}", "",
             *paragraph(entity.__doc__ if entity.__doc__
                        and not entity.__doc__.startswith(entity.__name__)
                        else None),
             *table(["Field", "Type", "Default"],
                    [(f"`{field.name}`", f"`{field.type}`", _default(field))
                     for field in dataclasses.fields(entity)])]
    if rules:
        lines += ["Refused on construction:", "",
                  *[f"- {rule}" for rule in rules], ""]
    return lines


def doc_domain() -> Doc:
    """05: the dataclasses every engine, verifier and adapter agrees on."""
    from vrp import model

    rules = _constructor_rules()
    entities = [value for value in vars(model).values()
                if isinstance(value, type) and dataclasses.is_dataclass(value)
                and value.__module__ == "vrp.model"]
    errors = [(f"`{value.__name__}`", f"`{value.__bases__[0].__name__}`",
               first_line(value.__doc__))
              for value in vars(model).values()
              if isinstance(value, type) and issubclass(value, Exception)
              and value.__module__ == "vrp.model"]
    body = [(f"{len(entities)} frozen dataclasses. Every one validates itself on "
            "construction, so an invalid instance cannot be built and no "
            "downstream stage has to re-check it."), "",
            "## Types", "",
            *table(["Type", "Fields"],
                   [(f"[`{entity.__name__}`](#{entity.__name__.lower()})",
                     len(dataclasses.fields(entity))) for entity in entities]),
            "## Errors", "", *table(["Exception", "Base", "Raised when"], errors),
            "## Detail", ""]
    for entity in entities:
        body += _entity(entity, rules.get(entity.__name__, []))
    return emit("05-domain-model.md", "05 — Domain model reference",
                ["vrp/model.py"], body)


