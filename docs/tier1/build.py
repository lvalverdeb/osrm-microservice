HELP_LINE = re.compile(r'^@echo "\s\s([a-z][\w/-]*)\s+-\s+(.+?)"$')
TARGET_LINE = re.compile(r"^([a-z][a-z0-9_-]*):(?!=)\s*([^#]*)(?:##\s*(.*))?$")
VARIABLE_LINE = re.compile(r"^([A-Z][A-Z0-9_]*)\s*\?=\s*(.*)$")


def _expand(described: dict[str, str]) -> dict[str, str]:
    """Split a combined help entry such as `jail-spike-up/-down` per target."""
    expanded: dict[str, str] = {}
    for key, description in described.items():
        names = key.split("/")
        stem = names[0].rsplit("-", 1)[0]
        for name in names:
            target = stem + name if name.startswith("-") else name
            expanded[target] = description
    return expanded


def doc_commands() -> Doc:
    """07: every make target, its prerequisites and its own description."""
    lines = read("Makefile").splitlines()
    described = _expand(dict(
        found.groups() for found in
        (HELP_LINE.match(line.strip()) for line in lines) if found))
    variables = [(f"`{found.group(1)}`", f"`{found.group(2)}`" if found.group(2)
                  else "*(empty)*")
                 for found in (VARIABLE_LINE.match(line) for line in lines)
                 if found]
    targets = []
    for found in (TARGET_LINE.match(line) for line in lines):
        if not found:
            continue
        name, needs, inline = found.groups()
        targets.append((f"`{name}`", " ".join((needs or "").split()) or "—",
                        (inline or described.get(name) or "—").strip()))
    body = [(f"{len(targets)} targets. The compose file is not at the repository "
            "root, so a bare `docker compose up` finds nothing: the targets are "
            "the interface."), "",
            "## Targets", "",
            *table(["Target", "Needs", "What it does"], targets),
            "## Variables you can override", "",
            *table(["Variable", "Default"], variables)]
    return emit("07-command-reference.md", "07 — Command reference",
                ["Makefile"], body)


