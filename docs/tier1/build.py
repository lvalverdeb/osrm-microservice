def _citations() -> dict[str, set[str]]:
    """Map every requirement identifier to the files that cite it."""
    hits: dict[str, set[str]] = {}
    for tree in SOURCE_TREES:
        for suffix in (".py", ".rs"):
            for path in sources_in(tree, suffix):
                for name in identifiers(path.read_text()):
                    hits.setdefault(name, set()).add(relative(path))
    return hits


def _citation_rows(hits: dict[str, set[str]], family: str) -> list[tuple]:
    """One family's identifiers, with where each is cited."""
    rows = []
    for name in sorted((key for key in hits if key.startswith(f"{family}-")),
                       key=sort_key):
        files = sorted(hits[name])
        shown = ", ".join(f"`{item}`" for item in files[:6])
        extra = f" +{len(files) - 6} more" if len(files) > 6 else ""
        rows.append((f"`{name}`", len(files), shown + extra))
    return rows


