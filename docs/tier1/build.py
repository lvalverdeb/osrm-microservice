def _grouped(paths: Sequence[Path]) -> dict[str, list[Path]]:
    """Group source files by the directory that holds them."""
    groups: dict[str, list[Path]] = {}
    for path in paths:
        groups.setdefault(relative(path.parent), []).append(path)
    return groups


