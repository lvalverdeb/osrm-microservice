def main(argv: Sequence[str]) -> int:
    """Generate every Tier 1 document.

    Args:
        argv: An optional destination directory, defaulting to this folder.

    Returns:
        A process exit code.
    """
    global DESTINATION
    if argv:
        DESTINATION = Path(argv[0]).resolve()
        DESTINATION.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(REPO))
    spec = openapi_document()
    docs = [doc_api(spec), doc_schemas(spec), doc_errors(), doc_config(),
            doc_domain(), doc_delivery_models(), doc_commands(), doc_modules(),
            doc_traceability(), doc_tests(), doc_examples(),
            doc_dependencies(), doc_baseline()]
    docs.append(index(docs))
    for doc in docs:
        print(f"wrote {DESTINATION.name}/{doc.slug}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
