SETTING = re.compile(
    r'^\s*(\w+)\s*:\s*([\w:<>, ]+?)\s*=\s*"([A-Z0-9_]+)"\s*/\s*"(.*)",\s*$')


def _settings_table() -> list[tuple[str, str, str, str, str]]:
    """Read the `settings!` declaration: section, name, type, default, notes."""
    block = re.search(r"settings! \{(.*?)\n\}", read("gateway/src/config.rs"),
                      re.DOTALL).group(1)
    section, doc, rows = "General", [], []
    for line in block.splitlines():
        heading = re.match(r"\s*// --- (.+?) ---", line)
        if heading:
            section = heading.group(1)
        elif line.strip().startswith("///"):
            doc.append(line.strip()[3:].strip())
        elif (found := SETTING.match(line)):
            _field, kind, name, default = found.groups()
            rows.append((section, name, kind, default, " ".join(doc)))
            doc = []
    return rows


def _app_env() -> dict[str, str]:
    """The values `deploy/env/app.env` ships to both deployments."""
    return dict(line.split("=", 1) for line in read("deploy/env/app.env").splitlines()
                if re.match(r"^[A-Z][A-Z0-9_]*=", line))


def _shipped_value(shipped: dict[str, str], name: str) -> str:
    """How `app.env` sets one setting, distinguishing unset from empty."""
    if name not in shipped:
        return "—"
    return f"`{shipped[name]}`" if shipped[name] else "*(empty)*"


def _undeclared_env() -> list[tuple[str, str]]:
    """Environment variables read outside the settings table."""
    declared = {name for _, name, _, _, _ in _settings_table()}
    found = set()
    for path in sources_in("gateway/src", ".rs"):
        for name in re.findall(r'env::var\("([A-Z][A-Z0-9_]*)"\)',
                               path.read_text()):
            if name not in declared:
                found.add((name, relative(path)))
    return sorted(found)


def _inert_settings() -> list[tuple[str, str]]:
    """Keys `app.env` carries that the gateway deliberately does not read."""
    block = re.search(r"INTENTIONALLY_UNUSED: &\[\(&str, &str\)\] = &\[(.*?)\];",
                      read("gateway/src/config.rs"), re.DOTALL)
    if not block:
        return []
    return [(f"`{name}`", reason) for name, reason in
            re.findall(r'\("([A-Z0-9_]+)",\s*"(.*?)"\)', block.group(1))]


def doc_config() -> Doc:
    """04: the settings surface, cross-checked against the shipped file."""
    shipped = _app_env()
    rows = [(f"`{name}`", section, f"`{kind}`",
             f"`{default}`" if default else "*(empty)*",
             _shipped_value(shipped, name),
             "yes" if shipped.get(name, default) == default else "**differs**")
            for section, name, kind, default, _notes in _settings_table()]
    detailed = [(f"`{name}`", notes)
                for _s, name, _k, _d, notes in _settings_table() if notes]
    body = [(f"{len(rows)} settings. Every one is read by name from the process "
            "environment, falls back to the committed default when unset or "
            "unparseable, and is matched case-insensitively."), "",
            "## Settings", "",
            *table(["Variable", "Group", "Type", "Default", "`app.env`",
                    "Agrees"], rows),
            "## Why a setting exists", "",
            *table(["Variable", "Note"], detailed),
            "## Read outside the settings table", "",
            *table(["Variable", "Site"], _undeclared_env()),
            "## Carried by `app.env` but deliberately not read", "",
            *table(["Variable", "Why not"], _inert_settings())]
    return emit("04-configuration-reference.md", "04 — Configuration reference",
                ["gateway/src/config.rs", "deploy/env/app.env"], body)


