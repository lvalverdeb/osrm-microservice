def _enum_variants(block: str) -> list[tuple[str, str]]:
    """Pair each `ApiError` variant with the doc comment above it."""
    variants: list[tuple[str, str]] = []
    doc: list[str] = []
    for line in block.splitlines():
        stripped = line.strip()
        if stripped.startswith("///"):
            doc.append(stripped[3:].strip())
        elif re.match(r"^[A-Z]\w*", stripped):
            variants.append((re.match(r"^[A-Z]\w*", stripped).group(0),
                             " ".join(doc)))
            doc = []
    return variants


def _arm_detail(arm: str) -> str:
    """Describe the `detail` body one match arm produces."""
    literal = re.search(r'"detail":\s*"([^"]+)"', arm)
    if literal:
        return f'`"{literal.group(1)}"`'
    if "ValidationError" in arm:
        return "a list of validation errors"
    if "upstream_detail" in arm:
        return "the engine's `code` and `message`, or a bare string"
    return "a list of validation errors" if "errors" in arm else "(structured)"


def _arm_status(arm: str) -> str:
    """The status one match arm answers with."""
    if "from_u16" in arm:
        return "the engine's own, or `INTERNAL_SERVER_ERROR` if it sent no valid one"
    found = re.search(r"StatusCode::([A-Z_]+)", arm)
    return f"`{found.group(1)}`" if found else "—"


def _status_arms(impl: str) -> list[tuple[str, str, str]]:
    """Read (case, status, detail) out of `IntoResponse for ApiError`."""
    pattern = re.compile(r"ApiError::(\w+)(?:\(OsrmError::(\w+))?")
    marks = list(pattern.finditer(impl))
    arms = []
    for index, mark in enumerate(marks):
        end = marks[index + 1].start() if index + 1 < len(marks) else len(impl)
        arm = impl[mark.start():end]
        case = mark.group(1) + (f" / {mark.group(2)}" if mark.group(2) else "")
        arms.append((case, _arm_status(arm), _arm_detail(arm)))
    return arms


def _statuses_elsewhere() -> list[tuple[str, str, str]]:
    """Statuses the gateway returns without going through `ApiError`."""
    rows = []
    for path in sources_in("gateway/src", ".rs"):
        lines = path.read_text().splitlines()
        for number, line in enumerate(lines):
            found = re.search(r"StatusCode::([A-Z_]+)", line)
            if not found or "error.rs" in relative(path):
                continue
            context = next((earlier.strip() for earlier in
                            reversed(lines[:number]) if "fn " in earlier), "")
            rows.append((found.group(1), f"`{relative(path)}:{number + 1}`",
                         context.replace("{", "").strip()))
    return rows


def doc_errors() -> Doc:
    """03: the failure taxonomy, and the status each case answers with."""
    source = read("gateway/src/error.rs")
    enum = re.search(r"pub enum ApiError \{(.*?)\n\}", source, re.DOTALL).group(1)
    impl = re.search(r"match self \{(.*?)\n        \}", source, re.DOTALL).group(1)
    body = ["## Failure cases", "",
            *table(["Variant", "Raised when"], _enum_variants(enum)),
            "## What the client receives", "",
            *table(["Case", "Status", "`detail`"], _status_arms(impl)),
            "## Statuses produced outside `ApiError`", "",
            ("Rate limiting, the panic guard, readiness and the method "
            "fallback answer directly."), "",
            *table(["Status", "Site", "Function"], _statuses_elsewhere())]
    return emit("03-error-catalogue.md", "03 — Error catalogue",
                ["gateway/src/error.rs", "gateway/src/main.rs",
                 "gateway/src/handlers.rs"], body)


