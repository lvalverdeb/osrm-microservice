def openapi_document() -> dict[str, Any]:
    """Fetch `/openapi.json` from a freshly started gateway.

    Read from a live instance rather than parsed out of the Rust, because the
    document is generated by `utoipa` from the same structs that deserialise
    requests: a parse of the annotations would be a second implementation of
    the thing being documented.

    Returns:
        The parsed OpenAPI document.

    Raises:
        SystemExit: when the gateway binary has not been built.
    """
    # `tests/conftest_gateway` is the one place that knows how to run the
    # binary -- its path, its readiness probe, its teardown. Imported here
    # rather than reimplemented, for the reason the parity harness gives.
    sys.path.insert(0, str(REPO / "tests"))
    import conftest_gateway
    import httpx

    if not conftest_gateway.BINARY.exists():
        raise SystemExit(
            "the gateway binary is missing; run\n"
            "  cargo build --manifest-path gateway/Cargo.toml\n"
            "or `make tier1`, which builds it first")
    # No routing engine: the document is served from the type system, and
    # `/health` answers "degraded" rather than failing, so readiness resolves.
    with conftest_gateway.gateway("http://127.0.0.1:1") as url:
        return httpx.get(f"{url}/openapi.json", timeout=30).json()


def type_name(schema: dict[str, Any]) -> str:
    """Render a schema node as a readable type, linking references by name."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f"[`{name}`](02-schema-catalogue.md#{name.lower()})"
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return type_name(schema["allOf"][0])
    for key in ("oneOf", "anyOf"):
        if key in schema:
            return " or ".join(type_name(part) for part in schema[key])
    if schema.get("type") == "array":
        return f"array of {type_name(schema.get('items', {}))}"
    if "enum" in schema:
        return " \\| ".join(f"`{value}`" for value in schema["enum"])
    kind = schema.get("type", "any")
    if isinstance(kind, list):
        return " or ".join(f"`{part}`" for part in kind)
    return f"`{kind}`"


def operations(spec: dict[str, Any]) -> list[tuple[str, str, dict[str, Any]]]:
    """Every (method, path, operation) the document declares, in path order."""
    return [(method.upper(), path, operation)
            for path, methods in sorted(spec["paths"].items())
            for method, operation in sorted(methods.items())]


def _request_body(operation: dict[str, Any]) -> list[str]:
    """The request body line, when the operation takes one."""
    content = operation.get("requestBody", {}).get("content", {})
    schema = content.get("application/json", {}).get("schema", {})
    return [f"**Request body:** {type_name(schema)}", ""] if schema else []


def _parameters(operation: dict[str, Any]) -> list[str]:
    """The parameter table, when the operation declares parameters."""
    parameters = operation.get("parameters", [])
    if not parameters:
        return []
    rows = [(item["name"], item["in"], type_name(item.get("schema", {})),
             "yes" if item.get("required") else "no",
             item.get("description", ""))
            for item in parameters]
    return ["**Parameters:**", "",
            *table(["Name", "In", "Type", "Required", "Meaning"], rows)]


def _responses(operation: dict[str, Any]) -> list[str]:
    """The status table every operation carries."""
    rows = [(status, response.get("description", ""))
            for status, response in sorted(operation.get("responses", {}).items())]
    return ["**Responses:**", "", *table(["Status", "Meaning"], rows)]


def _endpoint(method: str, path: str, operation: dict[str, Any]) -> list[str]:
    """One endpoint section: purpose, body, parameters, statuses."""
    return [f"### {method} `{path}`", "",
            *paragraph(operation.get("summary")),
            *paragraph(operation.get("description")),
            *_request_body(operation), *_parameters(operation),
            *_responses(operation)]


def doc_api(spec: dict[str, Any]) -> Doc:
    """01: every endpoint the gateway serves, from its own OpenAPI document."""
    live = [item for item in operations(spec) if not item[2].get("deprecated")]
    old = [item for item in operations(spec) if item[2].get("deprecated")]
    body = [(f"**{spec['info']['title']}** version `{spec['info']['version']}`. "
            f"{spec['info']['description']}"), "",
            "## Tags", "",
            *table(["Tag", "Covers"],
                   [(tag["name"], tag.get("description", ""))
                    for tag in spec.get("tags", [])]),
            "## Endpoints", "",
            *table(["Method", "Path", "Operation", "Tag", "Summary"],
                   [(method, f"`{path}`", f"`{op['operationId']}`",
                     ", ".join(op.get("tags", [])), first_line(op.get("summary")))
                    for method, path, op in live]),
            "## Deprecated aliases", "",
            "The same handlers, mounted without the version prefix.", "",
            *table(["Method", "Path"],
                   [(method, f"`{path}`") for method, path, _ in old]),
            "## Endpoint detail", ""]
    for method, path, operation in live:
        body += _endpoint(method, path, operation)
    return emit("01-api-reference.md", "01 — HTTP API reference",
                ["gateway/src/openapi.rs", "gateway/src/handlers.rs",
                 "gateway/src/main.rs"], body)


def _properties(schema: dict[str, Any]) -> list[str]:
    """The field table of an object schema."""
    required = set(schema.get("required", []))
    rows = [(f"`{name}`", type_name(field),
             "yes" if name in required else "no",
             f"`{field['default']!r}`" if "default" in field else "",
             field.get("description", ""))
            for name, field in schema.get("properties", {}).items()]
    return table(["Field", "Type", "Required", "Default", "Meaning"], rows)


def _schema_section(name: str, schema: dict[str, Any]) -> list[str]:
    """One schema: its description, then its fields or its permitted values."""
    lines = [f"### {name}", "", *paragraph(schema.get("description"))]
    if "enum" in schema:
        return [*lines, "Permitted values: "
                + ", ".join(f"`{value}`" for value in schema["enum"]), ""]
    if "properties" in schema:
        return [*lines, *_properties(schema)]
    return [*lines, f"Type: {type_name(schema)}", ""]


def doc_schemas(spec: dict[str, Any]) -> Doc:
    """02: every request and response type, field by field."""
    schemas = spec["components"]["schemas"]
    body = [("Every type the gateway deserialises a request into or serialises "
            "a response from. Constraints checked in `validate()` rather than "
            "by the type are described in the annotation, not enforced by the "
            "schema."), "",
            "## Index", "",
            *table(["Schema", "Kind", "Summary"],
                   [(f"[`{name}`](#{name.lower()})",
                     "enum" if "enum" in schema else schema.get("type", "union"),
                     summary(schema.get("description")))
                    for name, schema in sorted(schemas.items())]),
            "## Detail", ""]
    for name, schema in sorted(schemas.items()):
        body += _schema_section(name, schema)
    return emit("02-schema-catalogue.md", "02 — Request and response schemas",
                ["gateway/src/models.rs", "gateway/src/vrp/solve.rs"], body)


